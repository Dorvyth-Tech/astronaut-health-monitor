from django.db import models
from django.utils import timezone


class EnvironmentReading(models.Model):
    """
    Environmental and atmospheric condition reading for an astronaut habitat or planetary location.
    Real weather comes from OpenWeather API for Earth; Orbit, Moon, and Mars are simulated.
    """
    LOCATION_CHOICES = [
        ('earth', 'Earth'),
        ('orbit', 'Orbit'),
        ('moon', 'Moon'),
        ('mars', 'Mars'),
    ]

    location = models.CharField(max_length=20, choices=LOCATION_CHOICES, db_index=True)
    temperature = models.FloatField(help_text="Ambient temperature in °C")
    pressure = models.FloatField(help_text="Atmospheric / cabin pressure in kPa")
    humidity = models.FloatField(help_text="Relative humidity percentage (0-100%)")
    oxygen_percent = models.FloatField(help_text="Oxygen concentration percentage")
    co2_ppm = models.FloatField(help_text="Carbon dioxide concentration in parts per million (ppm)")
    radiation_level = models.FloatField(help_text="Radiation dose rate in µSv/h")
    is_simulated = models.BooleanField(default=True, help_text="True if generated by physics model, False if live Earth API")
    timestamp = models.DateTimeField(default=timezone.now, db_index=True)

    class Meta:
        verbose_name = "Environment Reading"
        verbose_name_plural = "Environment Readings"
        ordering = ['-timestamp']
        indexes = [
            models.Index(fields=['location', '-timestamp']),
        ]

    def __str__(self):
        source = "Simulated" if self.is_simulated else "Live OpenWeather"
        return f"[{self.get_location_display()}] Temp: {self.temperature:.1f}°C | CO2: {self.co2_ppm:.0f}ppm ({source})"

    @property
    def data_source(self):
        return "simulated" if self.is_simulated else "live"


class EnvironmentAlert(models.Model):
    """
    Safety alerts triggered when environmental factors exceed human physiological tolerances.
    """
    SEVERITY_CHOICES = [
        ('caution', 'Caution'),
        ('danger', 'Danger'),
    ]

    reading = models.ForeignKey(
        EnvironmentReading,
        on_delete=models.CASCADE,
        related_name='alerts'
    )
    message = models.CharField(max_length=255)
    severity = models.CharField(max_length=20, choices=SEVERITY_CHOICES, default='caution')
    created_at = models.DateTimeField(default=timezone.now, db_index=True)
    resolved = models.BooleanField(default=False, db_index=True)

    class Meta:
        verbose_name = "Environment Alert"
        verbose_name_plural = "Environment Alerts"
        ordering = ['-created_at']

    def __str__(self):
        return f"[{self.severity.upper()}] {self.message} ({'Resolved' if self.resolved else 'Active'})"


class SpaceWeatherEvent(models.Model):
    """
    Real solar and geomagnetic space weather events fetched from the NASA DONKI API
    (Space Weather Database Of Notifications, Knowledge, Information).
    Used to elevate radiation levels and trigger astronaut space weather alerts.
    """
    EVENT_TYPE_CHOICES = [
        ('flare', 'Solar Flare'),
        ('cme', 'Coronal Mass Ejection'),
        ('geomagnetic_storm', 'Geomagnetic Storm'),
        ('solar_particle', 'Solar Energetic Particle'),
    ]

    SEVERITY_CHOICES = [
        ('low', 'Low'),
        ('moderate', 'Moderate'),
        ('high', 'High'),
    ]

    event_type = models.CharField(max_length=30, choices=EVENT_TYPE_CHOICES, db_index=True)
    external_id = models.CharField(
        max_length=100,
        unique=True,
        db_index=True,
        help_text="Unique NASA DONKI activity ID (e.g. 2024-05-10T06:54:00-FLR-001)"
    )
    start_time = models.DateTimeField(db_index=True)
    intensity = models.CharField(
        max_length=50,
        help_text="Flare class (e.g. X1.8, M5.2), CME speed (km/s), or Kp index"
    )
    summary = models.TextField(blank=True, default='')
    severity = models.CharField(max_length=20, choices=SEVERITY_CHOICES, default='low', db_index=True)
    fetched_at = models.DateTimeField(default=timezone.now)

    class Meta:
        verbose_name = "Space Weather Event"
        verbose_name_plural = "Space Weather Events"
        ordering = ['-start_time']

    def __str__(self):
        return f"[{self.get_severity_display()}] {self.get_event_type_display()} ({self.intensity}) at {self.start_time.strftime('%Y-%m-%d %H:%M')}"

    @property
    def plain_language_advice(self):
        """Plain-language guidance for crew safety based on event type and severity."""
        if self.severity == 'high':
            if self.event_type == 'solar_particle':
                return "Critical solar proton flux: retreat to radiation storm shelter immediately; abort all EVAs."
            if self.event_type == 'flare':
                return "Major X-class solar flare: stay inside shielded habitat quarters; expect high-frequency radio blackout."
            if self.event_type == 'cme':
                return "Fast CME shock front inbound: prepare habitat storm shelter; power down non-essential avionics."
            return "Severe space weather event: minimize extravehicular operations and monitor acute dosimetry."
        elif self.severity == 'moderate':
            if self.event_type == 'flare':
                return "M-class solar flare detected: limit unshielded EVA duration; monitor telemetry."
            if self.event_type == 'geomagnetic_storm':
                return "Moderate geomagnetic storm: orbital comms degraded; minor navigational satellite anomalies possible."
            return "Moderate solar activity: maintain heightened situational dosimetry awareness."
        return "Nominal background solar activity: standard spaceflight operations authorized."
